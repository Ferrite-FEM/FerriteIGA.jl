
"""
    BezierGrid(mesh::NURBSMesh)
    BezierGrid(grid::Grid)
    BezierGrid(cells, nodes, weights, extraction_operators; cellsets, nodesets, facetsets, vertexsets)

A Ferrite grid (`<: Ferrite.AbstractGrid`) for isogeometric analysis. A `BezierGrid` is a
standard `Ferrite.Grid` in which

 - the nodes are the control points of the spline patch,
 - the cells are [`BezierCell`](@ref)s, one for each non-empty knot span,

and which additionally stores the NURBS weight of every control point and the
[`BezierExtractionOperator`](@ref) of every cell. Since it is a Ferrite grid, it can be used
with `DofHandler`, `ConstraintHandler`, `addfacetset!`, `getfacetset`, etc. exactly as in a
standard Ferrite program.

`getcoordinates(grid::BezierGrid, cellid)` returns a [`BezierCoords`](@ref) instead of a
vector of node coordinates.

# Constructors
 - `BezierGrid(mesh::NURBSMesh)`: create the grid from a NURBS patch, see
   [`generate_nurbs_patch`](@ref). This computes the Bézier extraction operators from the
   knot vectors. The orders of the patch must be equal in all parametric directions.
 - `BezierGrid(grid::Grid)`: wrap a standard Ferrite grid, with unit weights and without
   extraction operators. This can be used to mix isogeometric and standard cells.
 - `BezierGrid(cells, nodes, weights, extraction_operators; kwargs...)`: create the grid
   from its parts. `extraction_operators` contains one (possibly `nothing`) extraction
   operator per cell. The keyword arguments are the sets, as for `Ferrite.Grid`.

!!! note "Boundary sets"
    [`generate_nurbs_patch`](@ref) does not define any facet or node sets. Add them with
    `addfacetset!` and `addnodeset!`, which select facets based on the control points.
    For the geometries generated by FerriteIGA the boundary control points lie exactly on
    the (straight) boundaries, but in general control points need not lie on the
    geometry.

# Examples
```julia
mesh = generate_nurbs_patch(:plate_with_hole, (4, 4), 2)
grid = BezierGrid(mesh)
addfacetset!(grid, "left", x -> x[1] ≈ -4.0)
```

See the [BezierGrid topic guide](@ref beziergrid_topicguide) for more details.
"""
struct BezierGrid{dim,C<:Ferrite.AbstractCell,T<:Real} <: Ferrite.AbstractGrid{dim}
	grid    ::Ferrite.Grid{dim,C,T}
	weights ::Vector{T}
	beo     ::Vector{Optional{BezierExtractionOperator{T}}}

	#Alias from grid
	cells::Vector{C}
    nodes::Vector{Node{dim,T}}
    cellsets::Dict{String,OrderedSet{Int}}
    nodesets::Dict{String,OrderedSet{Int}}
    facetsets::Dict{String,OrderedSet{FacetIndex}}
    vertexsets::Dict{String,OrderedSet{VertexIndex}}

	function BezierGrid(grid::Ferrite.Grid{dim,C,T}, weights::Vector{T}, beo::Vector{Optional{BezierExtractionOperator{T}}}) where {dim,C,T}
		return new{dim,C,T}(
			grid, weights, beo,
			grid.cells, grid.nodes, grid.cellsets, grid.nodesets, grid.facetsets, grid.vertexsets, 
		)
	end
end

function BezierGrid(cells::Vector{C},
		nodes::Vector{Ferrite.Node{dim,T}},
		weights::AbstractVector{T},
		extraction_operators::Union{Vector{BezierExtractionOperator{T}}, Vector{Optional{BezierExtractionOperator{T}}}}; 
		cellsets::Dict{String,OrderedSet{Int}}             = Dict{String,OrderedSet{Int}}(),
		nodesets::Dict{String,OrderedSet{Int}}             = Dict{String,OrderedSet{Int}}(),
		facetsets::Dict{String,OrderedSet{FacetIndex}}      = Dict{String,OrderedSet{FacetIndex}}(),
		vertexsets::Dict{String,OrderedSet{VertexIndex}}   = Dict{String,OrderedSet{VertexIndex}}()) where {dim,C,T}

	extraction_operators = convert(Vector{Optional{BezierExtractionOperator{T}}}, extraction_operators)
	grid = Ferrite.Grid(cells, nodes; nodesets, cellsets, facetsets, vertexsets)

	return BezierGrid(grid, weights, extraction_operators)
end

function BezierGrid(mesh::NURBSMesh{pdim,sdim}) where {pdim,sdim}

	@assert allequal(mesh.orders)
	order = first(mesh.orders)
	N = size(mesh.IEN, 1)
    CellType = BezierCell{RefHypercube{pdim},order}
    ordering = _bernstein_ordering(CellType)
	
	cells = [CellType(Tuple(mesh.IEN[ordering,ie])) for ie in 1:getncells(mesh)]
	nodes = [Node(x)                                for x  in mesh.control_points]

    C, nbe = compute_bezier_extraction_operators(mesh.orders, mesh.knot_vectors)

	@assert nbe == length(cells)

	Cvec = bezier_extraction_to_vectors(C)

	return BezierGrid(cells, nodes, mesh.weights, Cvec)
end

function BezierGrid(grid::Ferrite.Grid{dim,C,T}) where {dim,C,T}
	weights = ones(T, getnnodes(grid))
	extraction_operator = Optional{BezierExtractionOperator{T}}[nothing for _ in 1:getncells(grid)]

	return BezierGrid(grid, weights, extraction_operator)
end

function Base.show(io::IO, ::MIME"text/plain", grid::BezierGrid)
    print(io, "$(typeof(grid)) with $(getncells(grid)) ")
    if isconcretetype(eltype(grid.cells))
        typestrs = [repr(eltype(grid.cells))]
    else
        typestrs = sort!(repr.(Set(typeof(x) for x in grid.cells)))
    end
    join(io, typestrs, '/')
    print(io, " cells and $(getnnodes(grid)) nodes (contorl points)")
end

"""
    get_nurbs_weights!(w::Vector, grid::BezierGrid, cellid::Int)
    get_nurbs_weights!(w::Vector, grid::BezierGrid, cell::AbstractCell)

Fill `w` with the NURBS weights of the control points of the cell, given either as its
index `cellid` or as the cell itself. `w` must have (at least) one entry per node of the
cell.

See also [`get_nurbs_weights`](@ref) and [`get_bezier_coordinates!`](@ref).
"""
Base.@propagate_inbounds function get_nurbs_weights!(w::Vector, grid::BezierGrid, cellid::Int)
    cell = grid.cells[cellid]
    get_nurbs_weights!(w, grid, cell)
end

Base.@propagate_inbounds function get_nurbs_weights!(w::Vector, grid::BezierGrid, cell::Ferrite.AbstractCell) 
	node_ids = Ferrite.get_node_ids(cell)
	nnodes = length(node_ids)
	@boundscheck checkbounds(Bool, w, 1:nnodes)
    @inbounds for i in 1:nnodes
        w[i] = grid.weights[node_ids[i]]
    end
end

"""
    get_nurbs_weights(grid::BezierGrid, cellid::Int)

Return a vector with the NURBS weights of the control points of cell `cellid`, in the same
order as the nodes of the cell. For a B-spline patch all weights are equal to one.

See also [`get_nurbs_weights!`](@ref) for an in-place version.
"""
function get_nurbs_weights(grid::BezierGrid, ic::Int)
	nodeids = collect(grid.cells[ic].nodes)
	return grid.weights[nodeids]
end

#Note: This is needed in order to get some stuff to work nicely in Ferrite.
Ferrite.get_coordinate_type(::BezierGrid{dim,C,T}) where {dim,C,T} = Vec{dim,T} 

function Ferrite.getcoordinates!(bc::BezierCoords{dim,T}, grid::BezierGrid, ic::Int) where {dim,T}
	get_bezier_coordinates!(bc.xb, bc.wb, bc.x, bc.w, grid, ic)
	bc.beo = grid.beo[ic]
	return bc
end

function Ferrite.getcoordinates(grid::BezierGrid{dim,C,T}, ic::Int) where {dim,C,T}

	n = Ferrite.nnodes_per_cell(grid, ic)
	w = zeros(T, n)
	wb = zeros(T, n)
	xb = zeros(Vec{dim,T}, n)
	x = zeros(Vec{dim,T}, n)
	
	bc = BezierCoords(xb, wb, x, w, grid.beo[ic])
	getcoordinates!(bc,grid,ic)

	return bc
end

"""
    get_bezier_coordinates!(xb, wb, x, w, grid::BezierGrid, cellid::Int)

Compute, in-place, the NURBS control points `x` and weights `w` of cell `cellid`, and the
corresponding Bézier control points `xb` and Bézier weights `wb`. The Bézier quantities are
obtained with the extraction operator ``\\mathbf{C}^e`` of the cell as

```math
w^b_j = \\sum_i C^e_{ij} w_i, \\qquad
\\boldsymbol{x}^b_j = \\frac{1}{w^b_j} \\sum_i C^e_{ij} w_i \\boldsymbol{x}_i.
```

If the cell has no extraction operator (e.g. a standard Ferrite cell), `xb` and `wb` are
copies of `x` and `w`. All vectors must have one entry per node of the cell.

Usually it is more convenient to call `getcoordinates(grid, cellid)`, which returns all of
this data as a [`BezierCoords`](@ref).
"""
function get_bezier_coordinates!(xb::AbstractVector{Vec{dim,T}}, 
								 wb::AbstractVector{T}, 
	                             x::AbstractVector{Vec{dim,T}},  
								 w::AbstractVector{T}, 
								 grid::BezierGrid, 
								 ic::Int) where {dim,T}
    n = length(xb)
	
	Ferrite.getcoordinates!(x, grid.grid, ic)
	get_nurbs_weights!(w, grid, ic)

	C = grid.beo[ic]
	if C === nothing #This is not an IGA cell
		xb .= x
		wb .= w
	else
		transform_coords!(xb, wb, C, x, w)
	end

	return nothing
end

"""
    get_bezier_coordinates(grid::BezierGrid, cellid::Int) -> (xb, wb, x, w)

Return the Bézier control points `xb`, the Bézier weights `wb`, the NURBS control points
`x` and the NURBS weights `w` of cell `cellid`.

See [`get_bezier_coordinates!`](@ref) for the definitions and an in-place version.
"""
function get_bezier_coordinates(grid::BezierGrid{dim,C,T}, ic::Int) where {dim,C,T}

	n = Ferrite.nnodes_per_cell(grid, ic)
	w = zeros(T, n)
	x = zeros(Vec{dim,T}, n)
	wb = zeros(T, n)
	xb = zeros(Vec{dim,T}, n)
	
	get_bezier_coordinates!(xb, wb, x, w, grid, ic)
	return xb, wb, x, w
end

"""
    get_nurbs_coordinates(grid::BezierGrid, cellid::Int)

Return the NURBS control points of cell `cellid`, i.e. the coordinates of the nodes of the
cell. Note that, in contrast to a Lagrange grid, control points do in general not lie on the
geometry. For the Bézier control points of the cell, see
[`get_bezier_coordinates`](@ref).
"""
function get_nurbs_coordinates(grid::BezierGrid{dim,C,T}, cell::Int) where {dim,C,T}
    nodeidx = grid.cells[cell].nodes
    return [grid.nodes[i].x for i in nodeidx]::Vector{Vec{dim,T}}
end

"""
    get_extraction_operator(grid::BezierGrid, cellid::Int)

Return the [`BezierExtractionOperator`](@ref) ``\\mathbf{C}^e`` of cell `cellid`, or
`nothing` if the cell does not have one (e.g. a standard Ferrite cell in a mixed grid).
"""
function get_extraction_operator(grid::BezierGrid, cellid::Int)
	return grid.beo[cellid]
end
